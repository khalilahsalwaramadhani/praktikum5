// Tipe data number

let x = 10; // number
console.log(x); // 10

let y = 3.14; // number
console.log(y); // 3.14
console.log(typeof y); // number

let nilai = "10.25"; // string
console.log(nilai);     
console.log(typeof nilai); // string

let nilaiNumerik = parseInt(nilai); // number
console.log(nilaiNumerik); // 10

let NilaiFloat = parseFloat(nilai); // number
console.log(NilaiFloat); // 10.25
console.log(typeof NilaiFloat); // number